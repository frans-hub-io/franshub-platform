import { DEFAULT_THEME, defaultCssVariablesResolver, mergeMantineTheme } from '@mantine/core';
import { fireEvent, screen } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import { renderThemed } from '../test/render';
import { applyInitialColorScheme, COLOR_SCHEME_STORAGE_KEY } from './colorScheme';
import { franshubCssVariablesResolver, franshubTheme } from './theme';
import { ThemeToggle } from './ThemeToggle';
import { useColorSchemeToggle } from './useColorSchemeToggle';

type Vars = Record<string, string>;

function changed(next: Vars, base: Vars): Vars {
  return Object.fromEntries(Object.entries(next).filter(([k, v]) => base[k] !== v));
}

function block(selector: string, vars: Vars): string {
  const lines = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`);
  return lines.length ? `${selector} {\n${lines.join('\n')}\n}\n` : '';
}

/**
 * The provider runs with `withCssVariables={false}` (no injected style tag), so the theme's CSS variables live in
 * a static file. It is generated here from `theme.ts`; after changing the theme run
 * `npx vitest run src/theme/theme.test.tsx -u`.
 */
function themeCss(): string {
  const merged = mergeMantineTheme(DEFAULT_THEME, franshubTheme);
  const base = defaultCssVariablesResolver(DEFAULT_THEME);
  const own = defaultCssVariablesResolver(merged);
  const extra = franshubCssVariablesResolver(merged);
  const vars = { ...own.variables, ...extra.variables };
  const light = { ...own.light, ...extra.light };
  const dark = { ...own.dark, ...extra.dark };
  return [
    '/* Generated by src/theme/theme.test.tsx from src/theme/theme.ts; do not edit by hand. */\n',
    block(':root', changed(vars, base.variables)),
    block(":root[data-mantine-color-scheme='light']", changed(light, base.light)),
    block(":root[data-mantine-color-scheme='dark']", changed(dark, base.dark)),
  ]
    .filter(Boolean)
    .join('\n');
}

function Scheme() {
  const { colorScheme } = useColorSchemeToggle();
  return <span data-testid="scheme">{colorScheme}</span>;
}

const root = () => document.documentElement.getAttribute('data-mantine-color-scheme');

describe('theme', () => {
  it('matches the static CSS variables', async () => {
    await expect(themeCss()).toMatchFileSnapshot('../styles/mantine-theme.css');
  });

  it('uses the brand primary color, fonts and radius', () => {
    expect(franshubTheme.primaryColor).toBe('fhPurple');
    expect(franshubTheme.fontFamily).toContain('Noto Sans');
    expect(franshubTheme.fontFamilyMonospace).toContain('JetBrains Mono');
    expect(franshubTheme.defaultRadius).toBe('md');
  });

  it('is dark by default when nothing is saved', () => {
    renderThemed(<Scheme />);
    expect(screen.getByTestId('scheme')).toHaveTextContent('dark');
    expect(root()).toBe('dark');
  });

  it('remembers the toggle in localStorage and restores it', () => {
    const first = renderThemed(
      <>
        <Scheme />
        <ThemeToggle />
      </>,
    );
    fireEvent.click(screen.getByRole('button', { name: 'Switch to light theme' }));
    expect(screen.getByTestId('scheme')).toHaveTextContent('light');
    expect(root()).toBe('light');
    expect(window.localStorage.getItem(COLOR_SCHEME_STORAGE_KEY)).toBe('light');
    first.unmount();

    renderThemed(<Scheme />);
    expect(screen.getByTestId('scheme')).toHaveTextContent('light');
  });

  it('works when localStorage throws', () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => {
      throw new Error('blocked');
    });
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => {
      throw new Error('blocked');
    });
    renderThemed(
      <>
        <Scheme />
        <ThemeToggle />
      </>,
    );
    expect(screen.getByTestId('scheme')).toHaveTextContent('dark');
    fireEvent.click(screen.getByRole('button', { name: 'Switch to light theme' }));
    expect(screen.getByTestId('scheme')).toHaveTextContent('light');
    expect(() => applyInitialColorScheme()).not.toThrow();
    expect(root()).toBe('dark');
  });

  it('applies the saved scheme before rendering', () => {
    window.localStorage.setItem(COLOR_SCHEME_STORAGE_KEY, 'light');
    applyInitialColorScheme();
    expect(root()).toBe('light');
  });
});
